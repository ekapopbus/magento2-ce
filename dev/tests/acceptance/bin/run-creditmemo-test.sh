#!/usr/bin/env bash
# Wrapper to run AdminCreateCreditMemoPartialRefundTest quickly with safe defaults
# Usage: ./dev/tests/acceptance/bin/run-creditmemo-test.sh [--use-token]
# It sources dev/tests/acceptance/.env (if present) and then runs the single generated Cest.

set -euo pipefail
# Start from the script directory and search upward for the repository root (where vendor/bin/codecept lives)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR=""
current_dir="$SCRIPT_DIR"
while [[ "$current_dir" != "/" ]]; do
  if [[ -x "$current_dir/vendor/bin/codecept" ]]; then
    ROOT_DIR="$current_dir"
    break
  fi
  # also accept composer.json as a heuristic for repo root
  if [[ -f "$current_dir/composer.json" && -d "$current_dir/vendor" ]]; then
    ROOT_DIR="$current_dir"
    break
  fi
  current_dir=$(dirname "$current_dir")
done
if [[ -z "$ROOT_DIR" ]]; then
  # fallback: use script's parent directory (best-effort)
  cd "$SCRIPT_DIR/.." || exit 1
  ROOT_DIR=$(pwd)
  echo "Warning: could not find vendor/bin/codecept while searching upwards; using $ROOT_DIR as ROOT_DIR" >&2
fi
# If .env exists, export its entries into the environment for the command
ENV_FILE="$ROOT_DIR/.env"
if [[ -f "$ENV_FILE" ]]; then
  # shellcheck disable=SC2013,SC2002
  while IFS= read -r line; do
    # skip comments and empty lines
    [[ "$line" =~ ^#.*$ ]] && continue
    [[ -z "$line" ]] && continue
    if [[ "$line" =~ = ]]; then
      name=$(echo "$line" | awk -F= '{print $1}' | xargs)
      value=$(echo "$line" | awk -F= '{print $2}')
      export "$name"="$value"
    fi
  done < "$ENV_FILE"
fi

# Ensure S3 helpers are disabled by default (safe for local dev)
export REMOTE_STORAGE_AWSS3_DISABLE=${REMOTE_STORAGE_AWSS3_DISABLE:-1}

# Provide sane AWS placeholder defaults so AWS SDK doesn't error if used
export CREDENTIAL_AWS_SECRETS_MANAGER_REGION=${CREDENTIAL_AWS_SECRETS_MANAGER_REGION:-us-east-1}
export AWS_REGION=${AWS_REGION:-us-east-1}
export AWS_ACCESS_KEY_ID=${AWS_ACCESS_KEY_ID:-test}
export AWS_SECRET_ACCESS_KEY=${AWS_SECRET_ACCESS_KEY:-test}

# Codeception test file (generated by MFTF)
TEST_FILE="tests/functional/Magento/_generated/default/AdminCreateCreditMemoPartialRefundTestCest.php:AdminCreateCreditMemoPartialRefundTest"
CODECEPTION_BIN="$(cd "$ROOT_DIR" && pwd)/vendor/bin/codecept"
CODECEPTION_CONFIG="-c dev/tests/acceptance/codeception.yml"

echo "Running AdminCreateCreditMemoPartialRefundTest with the following envs:"
env | grep -E 'REMOTE_STORAGE_AWSS3_DISABLE|MAGENTO_BASE_URL|MAGENTO_BACKEND_BASE_URL|MAGENTO_ADMIN|AWS_REGION|CREDENTIAL_AWS_SECRETS_MANAGER_REGION' || true

# Run the single test
"$CODECEPTION_BIN" run "$TEST_FILE" $CODECEPTION_CONFIG -vvv

exit $?

